package plugin;

import java.awt.Graphics2D;

/**
 * Интерфейс экземпляра загруженного робота.
 * Каждый робот на игровом поле — отдельный экземпляр этого интерфейса.
 *
 * Этот интерфейс определяет "жизненный цикл" робота:
 * - update() - обновление состояния (движение)
 * - draw() - отрисовка
 * - геттеры/сеттеры для позиции
 */
public interface RobotInstance {

    /**
     * Обновить состояние робота.
     * Вызывается ~60 раз в секунду из таймера.
     *
     * @param targetX целевая координата X (куда должен двигаться робот)
     * @param targetY целевая координата Y
     */
    void update(double targetX, double targetY);

    /**
     * Отрисовать робота.
     * Вызывается при каждой перерисовке экрана.
     *
     * @param g графический контекст
     * @param x координата X центра робота на экране
     * @param y координата Y центра робота на экране
     * @param isSelected true, если этот робот выбран пользователем
     */
    void draw(Graphics2D g, int x, int y, boolean isSelected);

    /**
     * Получить текущую позицию X.
     */
    double getX();

    /**
     * Получить текущую позицию Y.
     */
    double getY();

    /**
     * Получить направление робота в радианах.
     * Используется для совместимости с существующей системой.
     * 0 радиан = направление вправо, π/2 = вверх, π = влево, -π/2 = вниз.
     */
    double getDirection();

    /**
     * Установить позицию робота.
     * Используется при разрешении столкновений.
     */
    void setPosition(double x, double y);
}