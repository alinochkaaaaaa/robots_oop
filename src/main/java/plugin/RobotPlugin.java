package plugin;

/**
 * Интерфейс для загружаемых роботов.
 * Должен быть реализован в каждом JAR-файле с роботом.
 *
 * Этот интерфейс — точка входа для плагина. При загрузке JAR
 * менеджер ищет класс, реализующий этот интерфейс, и создаёт его экземпляр.
 */
public interface RobotPlugin {

    /**
     * Уникальный идентификатор типа робота.
     * Например: "four_wheel_robot", "tank_robot", "drone_robot"
     * Используется для идентификации плагина при сериализации.
     */
    String getRobotTypeId();

    /**
     * Отображаемое имя робота для UI.
     * Например: "4-колесный робот", "Танк", "Дрон"
     */
    String getDisplayName();

    /**
     * Создать новый экземпляр робота с начальными координатами.
     * Вызывается при добавлении нового робота на игровое поле.
     *
     * @param startX начальная позиция X
     * @param startY начальная позиция Y
     * @return новый экземпляр робота
     */
    RobotInstance createInstance(double startX, double startY);
}